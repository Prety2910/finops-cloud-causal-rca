"""Derive static service call graphs (caller -> callee) from RCAEval traces and write
configs/systems/{online_boutique,train_ticket}.yaml. Edge kept if observed in >= MIN_FRAC of cases.
Sock Shop has no traces in RCAEval, so its YAML stays hand-curated (verify against manifests)."""
import collections, sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path
import pandas as pd
import yaml

R = Path("data/processed/rcaeval")
MIN_FRAC = 0.05
NORMALISE = {"frontendservice": "frontend"}   # RE2-OB traces call the frontend 'frontendservice'


def edges(case):
    t = pd.read_parquet(R / case / "traces.parquet", columns=["spanID", "parentSpanID", "serviceName"])
    t["serviceName"] = t.serviceName.replace(NORMALISE)
    p = t[["spanID", "serviceName"]].rename(columns={"spanID": "parentSpanID", "serviceName": "caller"})
    j = t.dropna(subset=["parentSpanID"]).merge(p.drop_duplicates("parentSpanID"), on="parentSpanID")
    j = j[j.caller != j.serviceName]
    return set(zip(j.caller, j.serviceName))


def build(system, datasets):
    idx = pd.read_parquet(R / "cases.parquet")
    cases = idx[idx.dataset.isin(datasets) & idx.has_traces].case.tolist()
    with ProcessPoolExecutor(8) as ex:
        sets = list(ex.map(edges, cases))
    cnt = collections.Counter(e for s in sets for e in s)
    keep = sorted(e for e, n in cnt.items() if n / len(cases) >= MIN_FRAC)
    calls = collections.defaultdict(list)
    for a, b in keep:
        calls[a].append(b)
    return dict(calls), len(cases), {f"{a}->{b}": n for (a, b), n in cnt.items() if n / len(cases) < MIN_FRAC}


for system, ds, slo in [("online_boutique", ["RE2-OB", "RE3-OB"], ["frontend"]),
                        ("train_ticket", ["RE2-TT", "RE3-TT"], ["ts-ui-dashboard"])]:
    calls, n, dropped = build(system, ds)
    doc = {"system": system, "provenance": f"derived from traces of {ds} ({n} cases), edge kept if seen in >= {MIN_FRAC:.0%} of cases; "
           f"names normalised {NORMALISE}; generated by scripts/derive_call_graph.py. CAVEAT: only instrumented services emit spans, so this is a LOWER BOUND of the true call graph (e.g. OB: adservice, cartservice, shippingservice never appear)",
           "calls": {k: sorted(v) for k, v in sorted(calls.items())}, "slo_nodes": slo}
    Path(f"configs/systems/{system}.yaml").write_text(yaml.safe_dump(doc, sort_keys=False, width=100))
    print(system, "cases", n, "callers", len(calls), "edges", sum(len(v) for v in calls.values()), "rare edges dropped", len(dropped))
